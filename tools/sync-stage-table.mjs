import { readFileSync, writeFileSync } from "node:fs";
import { STAGES, INFINITE_SCENES } from "../js/logic.js";

const out = new URL("../unity/Assets/CatJumpShot/Rules/StageTable.cs", import.meta.url);

function str(value) {
  return `"${String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function row(stage) {
  const pool = stage.fakePool.map((kind) => str(kind)).join(", ");
  return [
    "        new(",
    [
      str(stage.id),
      stage.chapter,
      stage.index,
      str(stage.scene),
      str(stage.place.ko),
      str(stage.place.en),
      stage.fakeMin,
      stage.fakeMax,
      `new[] { ${pool} }`,
      stage.waitMin,
      stage.waitMax,
      stage.gapMin,
      stage.gapMax,
      stage.lateMs,
      stage.birds ? "true" : "false",
      stage.laundry ? "true" : "false",
      stage.flicker ? "true" : "false",
      stage.catCount,
      stage.hint ? "true" : "false",
    ].join(", "),
    ")",
  ].join("");
}

const scenes = INFINITE_SCENES.map((scene) => str(scene)).join(", ");
const text = `// Generated by tools/sync-stage-table.mjs from js/logic.js. Do not edit by hand.
namespace CatJumpShot.Rules
{
    public static class StageTable
    {
        public static readonly string[] InfiniteScenes = { ${scenes} };

        public static readonly StageDef[] All =
        {
${STAGES.map(row).join(",\n")}
        };

        public static StageDef ById(string id)
        {
            foreach (var stage in All)
            {
                if (stage.Id == id) return stage;
            }
            return null;
        }

        public static StageDef[] InChapter(int chapter)
        {
            var found = new System.Collections.Generic.List<StageDef>();
            foreach (var stage in All)
            {
                if (stage.Chapter == chapter) found.Add(stage);
            }
            return found.ToArray();
        }
    }
}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(out, "utf8");
  if (current !== text) {
    console.error("StageTable.cs is stale. Run: node tools/sync-stage-table.mjs");
    process.exit(1);
  }
  console.log("StageTable.cs matches js/logic.js");
} else {
  writeFileSync(out, text);
  console.log(`Wrote ${STAGES.length} stages`);
}
